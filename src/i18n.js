const mergeTranslations = (target, source) => {
  Object.entries(source).forEach(([key, value]) => {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      target[key] = mergeTranslations({ ...(target[key] || {}) }, value);
    } else {
      target[key] = value;
    }
  });
  return target;
};

